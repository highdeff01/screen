/**
 * Example workflows shipped with the console. Each one records how a raw user
 * request was refined into concrete Automation Workflow / Automation Step records.
 * Steps use the same field keys the Builder writes: type, name, params, timeoutMs, optional.
 */

const st = (id, type, name, params, extra = {}) => ({
  id,
  type,
  name,
  params,
  timeoutMs: extra.timeoutMs || 15000,
  optional: Boolean(extra.optional),
});

const policy = (overrides = {}) => ({
  onFailure: 'retry',
  maxRetries: 1,
  captureScreenshot: true,
  pauseBeforeRetryMs: 1200,
  notifyAgent: true,
  ...overrides,
});

