const DEFAULT_CHAIN_ROLES = ['scheduler', 'executor-a', 'verifier', 'reviewer'];

export const EXAMPLES = EXAMPLE_BLUEPRINTS.map((example) => {
  const patternTags = [
    ...new Set(
      [...(example.patternTags || []), ...(example.tags || [])]
        .map((tag) => String(tag).trim().toLowerCase())
        .filter(Boolean)
    ),
  ].slice(0, 8);
  return {
    ...example,
    patternTags,
    chainRoles: example.chainRoles || DEFAULT_CHAIN_ROLES,
  };
});

export function listExamples() {
  return EXAMPLES.map((example) => ({
    ...example,
    stepCount: example.steps.length,
    stepTypes: [...new Set(example.steps.map((s) => s.type))],
  }));
}

export function findExample(id) {
  return EXAMPLES.find((e) => e.id === id) || null;
}
